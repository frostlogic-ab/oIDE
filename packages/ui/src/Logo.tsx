import { useId } from 'react';
import { cn } from './cn.js';
import { LOGO_COLORS, LOGO_SHAPES } from './logoGeometry.js';

export interface LogoProps {
  /** `mark`: the symbol. `wordmark`: symbol + "oIDE" set in the surrounding font (Inter 700 in the app). */
  variant?: 'mark' | 'wordmark';
  /** Mark size in px. At 32 px and below the heavier small geometry is drawn. */
  size?: number;
  /**
   * `brand`: the fixed brand gradient (blue to violet, mint agent). It does not follow the
   * user-selected accent: the logo is the product's signature, not a theme colour.
   * `mono`: one colour, `currentColor` (tray-like spots, disabled or printed states).
   */
  tone?: 'brand' | 'mono';
  /** Accessible name for a standalone mark. Omit when visible text names the product next to it. */
  title?: string;
  className?: string;
}

/** The oIDE logo (docs/brand/README.md). Geometry: logoGeometry.ts, generated by tools/brand/build-brand.mjs. */
export function Logo({ variant = 'mark', size = 20, tone = 'brand', title, className }: LogoProps) {
  if (variant === 'wordmark') {
    return (
      <span className={cn('inline-flex items-center gap-2 whitespace-nowrap', className)}>
        <LogoMark size={size} tone={tone} />
        <span>oIDE</span>
      </span>
    );
  }
  return <LogoMark size={size} tone={tone} title={title} className={className} />;
}

function LogoMark({ size, tone, title, className }: { size: number; tone: 'brand' | 'mono'; title?: string; className?: string }) {
  const id = `oide-logo-${useId().replace(/[^a-zA-Z0-9_-]/g, '')}`;
  const s = size <= 32 ? LOGO_SHAPES.small : LOGO_SHAPES.full;
  const label = title ? { role: 'img', 'aria-label': title } : { 'aria-hidden': true as const };
  const common = { xmlns: 'http://www.w3.org/2000/svg', width: size, height: size, viewBox: '0 0 64 64', className: cn('shrink-0', className), focusable: 'false' as const, ...label };
  if (tone === 'mono') {
    return (
      <svg {...common} fill="currentColor" data-logo="mono">
        <path d={s.ring} />
        <circle cx={s.node.cx} cy={s.node.cy} r={s.node.r} />
        <circle cx={s.hub.cx} cy={s.hub.cy} r={s.hub.r} />
      </svg>
    );
  }
  const n = s.node;
  const h = s.hub;
  return (
    <svg {...common} data-logo="brand">
      <defs>
        <linearGradient id={`${id}-ring`} gradientUnits="userSpaceOnUse" x1="12" y1="10" x2="52" y2="56">
          <stop offset="0" stopColor={LOGO_COLORS.blue} />
          <stop offset="1" stopColor={LOGO_COLORS.violet} />
        </linearGradient>
        <radialGradient id={`${id}-agent`} gradientUnits="userSpaceOnUse" cx={n.cx - n.r * 0.35} cy={n.cy - n.r * 0.35} r={n.r * 1.35}>
          <stop offset="0" stopColor={LOGO_COLORS.mintHi} />
          <stop offset="1" stopColor={LOGO_COLORS.mint} />
        </radialGradient>
        <radialGradient id={`${id}-hub`} gradientUnits="userSpaceOnUse" cx={h.cx - h.r * 0.35} cy={h.cy - h.r * 0.35} r={h.r * 1.35}>
          <stop offset="0" stopColor={LOGO_COLORS.blueHi} />
          <stop offset="1" stopColor={LOGO_COLORS.blue} />
        </radialGradient>
      </defs>
      <path d={s.ring} fill={`url(#${id}-ring)`} />
      {s.highlight && <path d={s.highlight} fill="none" stroke="#FFFFFF" strokeOpacity={0.38} strokeWidth={1.5} strokeLinecap="round" />}
      <circle cx={n.cx} cy={n.cy} r={n.r} fill={`url(#${id}-agent)`} />
      <circle cx={h.cx} cy={h.cy} r={h.r} fill={`url(#${id}-hub)`} />
    </svg>
  );
}
